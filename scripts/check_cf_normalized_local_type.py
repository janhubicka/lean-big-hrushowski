#!/usr/bin/env python3
"""Audit complete normalization of finite ordered local C_F type data.

For every small graph on actual named old vertices P and a linearly
ordered fresh B, test the entire normalized candidate record:
complete induced graph, preserved old base, minimal d-closed step,
and exact old-neighbour d-closed support. The admissibility predicate
used here is concrete 2-sparsity, chosen only as an isomorphism-invariant
diagnostic. This does not assert that 2-sparsity characterizes C_F.
"""
from itertools import combinations, permutations

graphs=chosen_orders=qualifying_types=nonempty_supports=0
min_steps=exact_supports=0

def graph_data(p,n,E):
    size=p+n
    full=(1<<size)-1
    old=(1<<p)-1
    delta=tuple(2*s.bit_count()-sum(
        bool(s&(1<<u)) and bool(s&(1<<v)) for u,v in E)
        for s in range(1<<size))
    def closed(a,b):
        if a&~b: return False
        tail=b&~a
        t=tail
        while t:
            if delta[a]>=delta[a|t]:return False
            t=(t-1)&tail
        return True
    def hull(a,b):
        h=b
        for s in range(1<<size):
            if not a&~s and not s&~b and closed(s,b):
                h&=s
        return h
    def minimal(a,b):
        if a==b or not closed(a,b):return False
        return all(z==a or z==b or not closed(z,b)
                   for z in range(1<<size)
                   if not a&~z and not z&~b)
    N=sum(1<<v for v in range(p)
          if any(tuple(sorted((v,w))) in E
                 for w in range(p,size)))
    return (
        minimal(old,full),
        hull(N,old)==old,
        N,
        all(d>=0 for d in delta),
        delta,
    )

for p in range(3):
    for n in range(1,4):
        if p+n>5:continue
        size=p+n
        pairs=tuple(combinations(range(size),2))
        for mask in range(1<<len(pairs)):
            E={edge for i,edge in enumerate(pairs) if mask&(1<<i)}
            graphs+=1
            before=graph_data(p,n,E)
            if before[0]:min_steps+=1
            if before[1]:exact_supports+=1
            for order in permutations(range(n)):
                chosen_orders+=1
                rename=tuple(range(p))+tuple(p+i for i in order)
                Eprime={tuple(sorted((rename[u],rename[v])))
                        for u,v in pairs if (u,v) in E}
                after=graph_data(p,n,Eprime)
                assert before[0]==after[0]
                assert before[1]==after[1]
                assert before[2]==after[2]
                assert before[3]==after[3]
                assert sorted(rename)==list(range(size))
                # The induced original graph is recovered exactly.
                assert {tuple(sorted((rename.index(u),rename.index(v))))
                        for u,v in Eprime}==E
                if before[0] and before[1] and before[3]:
                    qualifying_types+=1
                    if before[2]:nonempty_supports+=1
                    # The complete minimal block is generated by each
                    # new vertex (the verified finite generators lemma).
                    old=(1<<p)-1
                    assert all(after[4][old|(1<<v)]>after[4][old]
                               for v in range(p,size))

assert qualifying_types>0 and nonempty_supports>0
print({
    "actual_finite_graphs":graphs,
    "chosen_fresh_orders":chosen_orders,
    "minimal_dclosed_source_steps":min_steps,
    "exact_support_source_codes":exact_supports,
    "normalized_allowed_local_records":qualifying_types,
    "records_with_nonempty_support":nonempty_supports,
    "normalized_minimality_support_or_order_mismatches":0
})
